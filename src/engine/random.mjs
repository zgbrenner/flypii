/** Small deterministic PRNG. This is reproducibility machinery, not cryptography. */
export function rng(seed=42){
 let a=seed>>>0;
 return ()=>{a+=0x6D2B79F5;let t=a;t=Math.imul(t^(t>>>15),t|1);t^=t+Math.imul(t^(t>>>7),t|61);return ((t^(t>>>14))>>>0)/4294967296;};
}
export function shuffle(values, random){
 const a=Array.from(values);for(let i=a.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[a[i],a[j]]=[a[j],a[i]];}return a;
}
